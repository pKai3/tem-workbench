const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const window={};vm.runInNewContext(fs.readFileSync('web/aztec-analysis.js','utf8').split('window.aztecComparisonState=')[0],{window,Date});
const api=window.aztecLabelColours,values=new Map(),storage={readRaw:key=>values.get(key),writeRaw:(key,value)=>values.set(key,value)};
let memory=api.create(storage);
memory.remember({colour:'#ABC',label:' ST ',sample:'sample one'});
memory.remember({colour:'#123456',label:'unrelated'});
memory.remember({colour:'#abcdef',label:'AB',sample:'ST'});
memory=api.create(storage);
let choices=memory.suggestions([{colour:'#ff0000',label:'STA'},{colour:'#aabbcc',label:'ST'}],{label:'st',sample:'sample one'});
assert.equal(choices[0].colour,'#aabbcc','Label match beats more recent unrelated colours');
assert.equal(choices[1].colour,'#abcdef','Sample names also match export labels');
assert.equal(choices[2].colour,'#ff0000','In-use colours precede unrelated recent ones');
assert.equal(choices[3].colour,'#123456');
assert.equal(choices.filter(c=>c.colour==='#aabbcc').length,1,'Same colour is suggested only once');
assert.equal(choices.find(c=>c.colour==='#ff0000').reason,'In use','ST does not loosely match STA');
const before=[...values.values()][0];memory.seed([{colour:'#aabbcc',label:'ST',sample:'sample one'}]);assert.equal([...values.values()][0],before,'Opening the picker must not promote existing history');
memory.remember({colour:'invalid',label:'ST'});assert.equal([...values.values()][0],before);
memory.seed([{colour:'#fed',label:'Different',sample:'  Sample   One '}]);
choices=memory.suggestions([],{label:'unknown',sample:'sample one'});assert.equal(choices[0].rank,1);assert.equal(choices[1].rank,1);
for(let i=0;i<160;i++)memory.remember({colour:'#'+i.toString(16).padStart(6,'0'),label:'sample '+i});
assert.equal(JSON.parse([...values.values()][0]).length,128,'History is bounded');
assert.equal(memory.suggestions([],{label:'',sample:''}).length,24,'Popup suggestions are bounded');
assert.deepEqual(api.create({readRaw:()=>'{broken'}).suggestions([],{}).length,0);
console.log('Colour memory survives reload, matches names, ranks in-use/recent colours, deduplicates and bounds history.');

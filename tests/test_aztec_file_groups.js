const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('web/aztec.js','utf8'),context={};
vm.createContext(context);vm.runInContext(source.slice(source.indexOf('function fileGroups('),source.indexOf('function navigationFile(')),context);
const parent={path:'/data/Native.oipx',name:'Native.oipx',relative_path:'EDX/Native.oipx',project:'G9-HT',kind:'OIPX'};
const child=(name)=>({path:'/data/h5oina/'+name,relative_path:'EDX/h5oina/'+name,name,project:'G9-HT',kind:'H5OINA',parent_path:parent.path});
const a=child('Native ST Site 3 Line Data 3.h5oina'),b=child('Native STA Overview Map Data 1.h5oina');
const unrelated={...child('Separate.h5oina'),parent_path:undefined};
const files=[a,parent,b,unrelated],group=context.fileGroups;
const all=group(files,'');
assert.equal(all.length,2,'Related exports do not appear as independent roots');
assert.equal(all[0].file,parent);assert.deepEqual(Array.from(all[0].exports),[a,b]);
assert.equal(all[1].file,unrelated);
const search=group(files,'site 3');
assert.equal(search.length,1);assert.equal(search[0].file,parent,'Searching a child preserves its native parent');
assert.deepEqual(Array.from(search[0].exports),[a]);assert.equal(search[0].total,2);
assert.equal(group(files,'g9-ht')[0].exports.length,2,'Project search includes its exports');
assert.equal(group(files,'unknown').length,0);
assert.equal(group([a,b],'').length,2,'Exports remain reachable if their parent is filtered out or missing');
assert.equal(files.length,4);assert.equal(a.name,'Native ST Site 3 Line Data 3.h5oina','Display grouping never rewrites a source');
context.state={files,nativeFile:{catalogue:{source:{path:parent.path}}},file:{catalogue:{source:{path:a.path}}}};
vm.runInContext(source.slice(source.indexOf('function navigationFile('),source.indexOf('function renderFiles(')),context);
assert.equal(context.navigationFile(),context.state.nativeFile,'An opened export keeps its native project navigation');
context.state.file={catalogue:{source:{path:unrelated.path}}};
assert.equal(context.navigationFile(),context.state.file,'Standalone exports do not inherit the previous project');
context.state.file={catalogue:{source:{path:a.path}}};context.state.files=[a,b];
// The cached native context can still be used while the export remains associated.
assert.equal(context.navigationFile(),context.state.nativeFile);
context.state.files=[{...a,parent_path:undefined},b];
assert.equal(context.navigationFile(),context.state.file,'A rescan that removes the association removes stale navigation');
console.log('Project exports stay out of top-level Files; search, native context and orphaned-file access are retained.');
